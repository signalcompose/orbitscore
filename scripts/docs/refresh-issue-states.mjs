#!/usr/bin/env node
/**
 * 計画文書が参照している issue の open/closed を GitHub から取り、スナップショットへ書く（#814）。
 *
 * 🔴 なぜスナップショットにするか: `tests/docs/planning-issue-state.spec.ts` は CI で走る。
 * テストが GitHub API を叩くと、ネットワークとレート制限が**テストの赤の原因**になり、
 * 「赤の帰属ができなくなる」— #801 で 1 日 2 回踏んだのと同じクラスの失敗を持ち込む。
 *
 * 更新の仕方: `node scripts/docs/refresh-issue-states.mjs`（`gh` の認証が要る）。
 * 差分が出たらコミットする。**スナップショットが古いこと自体はテストを赤にしない** —
 * 赤にするのは「**閉じた issue を未完了の語で書いている行**」だけである。
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, '../..')
const OUT = path.join(repoRoot, 'docs/planning/issue-states.json')

const states = {}
for (const state of ['open', 'closed']) {
  const raw = execFileSync(
    'gh',
    ['issue', 'list', '--state', state, '--limit', '1000', '--json', 'number'],
    { cwd: repoRoot, encoding: 'utf8' },
  )
  for (const { number } of JSON.parse(raw)) states[number] = state
}

const numbers = Object.keys(states)
  .map(Number)
  .sort((a, b) => a - b)
const payload = {
  note: 'Generated by scripts/docs/refresh-issue-states.mjs — do not hand-edit.',
  generatedAt: new Date().toISOString().slice(0, 10),
  closed: numbers.filter((n) => states[n] === 'closed'),
}
fs.writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`)
console.log(`wrote ${OUT}: ${payload.closed.length} closed issues (as of ${payload.generatedAt})`)
